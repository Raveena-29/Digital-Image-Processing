import cv2
import numpy as np
import matplotlib.pyplot as plt

# (a) Read and display image
img = cv2.imread('image.jpg')
img = cv2.cvtColor(img, cv2.COLOR_BGR2RGB)

plt.imshow(img)
plt.title('Original Image')
plt.show()

# (b) Resize image
resized = cv2.resize(img, (200, 200))

plt.imshow(resized)
plt.title('Resized Image')
plt.show()

# (c) Convert colour image to grayscale
gray = cv2.cvtColor(img, cv2.COLOR_RGB2GRAY)

plt.imshow(gray, cmap='gray')
plt.title('Grayscale Image')
plt.show()

# (d) Convert grayscale image to black and white
_, binary = cv2.threshold(gray, 127, 255, cv2.THRESH_BINARY)

plt.imshow(binary, cmap='gray')
plt.title('Black and White Image')
plt.show()

# Draw image profile
row = gray.shape[0] // 2

plt.plot(gray[row, :])
plt.title('Image Profile')
plt.xlabel('Pixel Position')
plt.ylabel('Intensity')
plt.show()

# (e) Separate R, G and B planes
r, g, b = cv2.split(img)

plt.subplot(1, 3, 1)
plt.imshow(r, cmap='gray')
plt.title('Red Plane')

plt.subplot(1, 3, 2)
plt.imshow(g, cmap='gray')
plt.title('Green Plane')

plt.subplot(1, 3, 3)
plt.imshow(b, cmap='gray')
plt.title('Blue Plane')

plt.show()

# (f) Create colour image using R, G and B planes
merged = cv2.merge([r, g, b])

plt.imshow(merged)
plt.title('Merged Image')
plt.show()

# (g) Write 2-D data into an image file
data = np.array([[0, 50, 100],
                 [100, 150, 200],
                 [200, 250, 255]], dtype=np.uint8)

cv2.imwrite('output.png', data)

plt.imshow(data, cmap='gray', vmin=0, vmax=255)
plt.title('2-D Data Image')
plt.show()