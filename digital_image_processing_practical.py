"""#Practical 5: Histogram and Equalization"""

import cv2
import numpy as np
import matplotlib.pyplot as plt

# Read grayscale image
img = cv2.imread('image.jpg', 0)

# (a) Using inbuilt functions

hist1 = cv2.calcHist([img], [0], None, [256], [0, 256])
equalized1 = cv2.equalizeHist(img)

# (b) Without using inbuilt functions

# Calculate histogram
hist2 = np.zeros(256)

for pixel in img.ravel():
    hist2[pixel] += 1

# Calculate PDF
pdf = hist2 / img.size

# Calculate CDF
cdf = np.zeros(256)
cdf[0] = pdf[0]

for i in range(1, 256):
    cdf[i] = cdf[i-1] + pdf[i]

# Calculate new intensity values
mapping = np.round(255 * cdf).astype(np.uint8)

# Generate equalized image
equalized2 = mapping[img]

# Display all outputs
plt.figure(figsize=(12, 8))

plt.subplot(2, 3, 1)
plt.imshow(img, cmap='gray', vmin=0, vmax=255)
plt.title('Original Image')

plt.subplot(2, 3, 2)
plt.plot(hist1)
plt.title('Inbuilt Histogram')

plt.subplot(2, 3, 3)
plt.imshow(equalized1, cmap='gray', vmin=0, vmax=255)
plt.title('Inbuilt Equalization')

plt.subplot(2, 3, 4)
plt.imshow(img, cmap='gray', vmin=0, vmax=255)
plt.title('Original Image')

plt.subplot(2, 3, 5)
plt.plot(hist2)
plt.title('Manual Histogram')

plt.subplot(2, 3, 6)
plt.imshow(equalized2, cmap='gray', vmin=0, vmax=255)
