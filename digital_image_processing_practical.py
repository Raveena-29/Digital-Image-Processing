"""#Practical 9: Frequency Domain Filtering"""

import cv2
import numpy as np
import matplotlib.pyplot as plt

# Read grayscale image
img = cv2.imread('image.jpg', 0)

# (a) Fast Fourier Transform
f = np.fft.fft2(img)
fshift = np.fft.fftshift(f)

# Magnitude spectrum
magnitude = 20 * np.log(1 + np.abs(fshift))

# Find centre of image
h, w = img.shape
cy, cx = h // 2, w // 2

# (b) Low-pass filter
lp_mask = np.zeros((h, w), np.uint8)
cv2.circle(lp_mask, (cx, cy), 30, 1, -1)

lp = fshift * lp_mask

# Inverse Fourier Transform
lowpass = np.fft.ifft2(np.fft.ifftshift(lp))
lowpass = np.real(lowpass)

# (c) High-pass filter
hp_mask = 1 - lp_mask

hp = fshift * hp_mask

# (d) Inverse Fourier Transform
highpass = np.fft.ifft2(np.fft.ifftshift(hp))
highpass = np.abs(highpass)

# Display all images
plt.figure(figsize=(12, 8))

plt.subplot(2, 3, 1)
plt.imshow(img, cmap='gray')
plt.title('Original Image')

plt.subplot(2, 3, 2)
plt.imshow(magnitude, cmap='gray')
plt.title('Magnitude Spectrum')

plt.subplot(2, 3, 3)
plt.imshow(lp_mask, cmap='gray')
plt.title('Low Pass Mask')

plt.subplot(2, 3, 4)
plt.imshow(lowpass, cmap='gray')
plt.title('Low Pass Filter')

plt.subplot(2, 3, 5)
plt.imshow(hp_mask, cmap='gray')
plt.title('High Pass Mask')

plt.subplot(2, 3, 6)
plt.imshow(highpass, cmap='gray')
plt.title('High Pass Filter')

plt.tight_layout()
plt.show()

"""#Practical 10: Edge Detection"""

import cv2
import numpy as np
import matplotlib.pyplot as plt

# Read grayscale image
img = cv2.imread('image.jpg', 0)

# (a) Roberts operator
rx = np.array([[1, 0],
               [0, -1]])

ry = np.array([[0, 1],
               [-1, 0]])

x = cv2.filter2D(img, cv2.CV_32F, rx)
y = cv2.filter2D(img, cv2.CV_32F, ry)

roberts = cv2.magnitude(x, y)

# (b) Prewitt operator
px = np.array([[-1, 0, 1],
               [-1, 0, 1],
               [-1, 0, 1]])

py = np.array([[-1, -1, -1],
               [ 0,  0,  0],
               [ 1,  1,  1]])

x = cv2.filter2D(img, cv2.CV_32F, px)
y = cv2.filter2D(img, cv2.CV_32F, py)

prewitt = cv2.magnitude(x, y)

# (c) Sobel operator
x = cv2.Sobel(img, cv2.CV_32F, 1, 0, ksize=3)
y = cv2.Sobel(img, cv2.CV_32F, 0, 1, ksize=3)

sobel = cv2.magnitude(x, y)

# (d) Laplacian operator
laplacian = cv2.Laplacian(img, cv2.CV_32F)
laplacian = cv2.convertScaleAbs(laplacian)

# (e) Canny edge detector
canny = cv2.Canny(img, 100, 200)

# Display all images
plt.figure(figsize=(12, 8))

plt.subplot(2, 3, 1)
plt.imshow(img, cmap='gray')
plt.title('Original Image')

plt.subplot(2, 3, 2)
plt.imshow(roberts, cmap='gray')
plt.title('Roberts Operator')

plt.subplot(2, 3, 3)
plt.imshow(prewitt, cmap='gray')
plt.title('Prewitt Operator')

plt.subplot(2, 3, 4)
plt.imshow(sobel, cmap='gray')
plt.title('Sobel Operator')

plt.subplot(2, 3, 5)
plt.imshow(laplacian, cmap='gray')
plt.title('Laplacian Operator')

plt.subplot(2, 3, 6)
plt.imshow(canny, cmap='gray')
plt.title('Canny Edge Detector')

plt.tight_layout()
plt.show()

"""#Practical 11: Morphological Operations"""

