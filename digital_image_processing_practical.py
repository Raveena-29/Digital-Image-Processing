"""#Practical 7: Noise Models and Restoration"""

import cv2
import numpy as np
import matplotlib.pyplot as plt
from scipy.signal import wiener

# Read grayscale image
img = cv2.imread('image.jpg', 0)

# (a) Image restoration
noise = np.random.normal(0, 25, img.shape)
gaussian = np.clip(img + noise, 0, 255).astype(np.uint8)

restored = cv2.blur(gaussian, (3, 3))

# (b) Remove salt and pepper noise
sp = img.copy()
r = np.random.random(img.shape)

sp[r < 0.02] = 0
sp[r > 0.98] = 255

removed = cv2.medianBlur(sp, 3)

# (c) Minimize Gaussian noise
gaussian_removed = cv2.GaussianBlur(gaussian, (5, 5), 0)

# (d) Median and Wiener filters
median = cv2.medianBlur(sp, 5)

wiener_img = wiener(gaussian.astype(float), (5, 5))
wiener_img = np.clip(wiener_img, 0, 255)

